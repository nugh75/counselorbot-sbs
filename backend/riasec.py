def ordered_codes(totals: Mapping[str, float]) -> list[str]:
    """Area codes by descending total, ties in canonical Holland order R-I-A-S-E-C."""
    return sorted(AREAS, key=lambda code: (-float(totals.get(code, 0)), AREAS.index(code)))


def holland_code(totals: Mapping[str, float]) -> str:
    """Deterministic three-letter high-point code (explicit tie rule)."""
    return "".join(ordered_codes(totals)[:3])


def top_codes(totals: Mapping[str, float], count: int = 3) -> list[str]:
    return ordered_codes(totals)[:count]


def dimension_payload(totals: Mapping[str, float]) -> list[dict]:
    return [
        {
            "code": code,
            "raw_total": int(round(float(totals.get(code, 0)))),
            "max_total": MAX_AREA_TOTAL,
        }
        for code in AREAS
    ]
