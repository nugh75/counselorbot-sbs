import importlib.util
from pathlib import Path
import json
import tempfile
import unittest

spec = importlib.util.spec_from_file_location('sync_version', Path(__file__).resolve().parents[1] / 'sync-version.py')
sync_version = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sync_version)


def write(root, name, text):
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


class SyncVersionTests(unittest.TestCase):
    staler_version = '0.1.0'

    def make_repo(self, folder, version='0.2.0'):
        root = Path(folder)
        older = self.staler_version
        write(root, 'VERSION', version + '\n')
        write(root, 'frontend/package.json', json.dumps({'name': 'frontend', 'version': older}, indent=2) + '\n')
        write(root, 'frontend/package-lock.json', json.dumps(
            {'name': 'frontend', 'version': older, 'packages': {'': {'version': older}}}, indent=2) + '\n')
        write(root, 'desktop/teacher/package.json', json.dumps(
            {'name': 'counselorbot-teacher', 'version': older}, indent=2) + '\n')
        write(root, 'desktop/teacher/package-lock.json', json.dumps(
            {'name': 'counselorbot-teacher', 'version': older, 'lockfileVersion': 3,
             'packages': {'': {'name': 'counselorbot-teacher', 'version': older},
                          'node_modules/@tauri-apps/cli': {'version': '2.12.4'}}}, indent=2) + '\n')
        write(root, 'backend/version.py', '"""doc"""\n__version__ = "%s"\n' % older)
        write(root, 'desktop/teacher/src-tauri/tauri.conf.json', json.dumps({'version': older}, indent=2) + '\n')
        # Manifest reale: `version = "2"` di tauri-build/tauri non deve toccarsi.
        write(root, 'desktop/teacher/src-tauri/Cargo.toml', '\n'.join([
            '[package]',
            'name = "counselorbot-teacher"',
            'version = "' + older + '"',
            'edition = "2021"',
            'publish = false',
            '',
            '[build-dependencies]',
            'tauri-build = { version = "2", features = [] }',
            '',
            '[dependencies]',
            'tauri = { version = "2", features = [] }',
            'serde_json = "1"',
            '',
            '[profile.release]',
            'strip = true',
        ]) + '\n')
        # Lock con una dipendenza esterna e la voce del crate dell'app in coda.
        write(root, 'desktop/teacher/src-tauri/Cargo.lock', '\n'.join([
            '# This file is automatically @generated by Cargo.',
            '# It is not intended for manual editing.',
            'version = 4',
            '',
            '[[package]]',
            'name = "libc"',
            'version = "0.2.155"',
            'source = "registry+https://github.com/rust-lang/crates.io-index"',
            'checksum = "fakenote"',
            '',
            '[[package]]',
            'name = "counselorbot-teacher"',
            'version = "' + older + '"',
            'dependencies = [',
            ' "libc 0.2.155",',
            ']',
        ]) + '\n')
        return root

    def all_targets(self, root):
        return sorted(
            sync_version.json_targets(root) + sync_version.cargo_targets(root) +
            sync_version.cargo_lock_targets(root) + [sync_version.BACKEND])

    def test_check_reports_every_stale_target_without_writing(self):
        with tempfile.TemporaryDirectory() as folder:
            root = self.make_repo(folder)
            before = {n: (root / n).read_bytes() for n in self.all_targets(root)}
            _, stale = sync_version.sync(root, write=False)
            self.assertEqual(sorted(stale), self.all_targets(root))
            # `--check` non scrive: i metadati desktop restano byte per byte.
            self.assertEqual(before, {n: (root / n).read_bytes() for n in self.all_targets(root)})

    def test_write_propagates_desktop_metadata_then_check_is_clean(self):
        with tempfile.TemporaryDirectory() as folder:
            root = self.make_repo(folder)
            sync_version.sync(root, write=True)
            self.assertEqual(sync_version.sync(root, write=False), ('0.2.0', []))
            manifest = (root / 'desktop/teacher/src-tauri/Cargo.toml').read_text()
            self.assertIn('version = "0.2.0"', manifest)
            for frozen in ('tauri-build = { version = "2", features = [] }',
                           'tauri = { version = "2", features = [] }',
                           'serde_json = "1"'):
                self.assertIn(frozen, manifest)
            lock = (root / 'desktop/teacher/src-tauri/Cargo.lock').read_text()
            self.assertIn('version = 4', lock)
            self.assertIn('name = "counselorbot-teacher"\nversion = "0.2.0"', lock)
            self.assertIn('name = "libc"\nversion = "0.2.155"', lock)
            lockjson = json.loads((root / 'desktop/teacher/package-lock.json').read_text())
            self.assertEqual((lockjson['version'], lockjson['packages']['']['version']), ('0.2.0', '0.2.0'))
            self.assertEqual(lockjson['packages']['node_modules/@tauri-apps/cli']['version'], '2.12.4')
            self.assertIn('__version__ = "0.2.0"', (root / 'backend/version.py').read_text())

    def test_sync_is_idempotent(self):
        with tempfile.TemporaryDirectory() as folder:
            root = self.make_repo(folder)
            sync_version.sync(root, write=True)
            self.assertEqual(sync_version.sync(root, write=True), ('0.2.0', []))

    def test_desktop_targets_are_optional_when_files_are_absent(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            write(root, 'VERSION', '0.2.0\n')
            write(root, 'frontend/package.json', json.dumps({'name': 'frontend', 'version': '0.1.0'}, indent=2) + '\n')
            write(root, 'frontend/package-lock.json', json.dumps(
                {'name': 'frontend', 'version': '0.1.0', 'packages': {'': {'version': '0.1.0'}}}, indent=2) + '\n')
            write(root, 'backend/version.py', '"""doc"""\n__version__ = "0.1.0"\n')
            _, stale = sync_version.sync(root, write=False)
            self.assertEqual(sorted(stale), ['backend/version.py', 'frontend/package-lock.json', 'frontend/package.json'])

    def test_missing_crate_entry_in_lock_fails_closed(self):
        with tempfile.TemporaryDirectory() as folder:
            root = self.make_repo(folder)
            lock = (root / 'desktop/teacher/src-tauri/Cargo.lock').read_text()
            write(root, 'desktop/teacher/src-tauri/Cargo.lock', lock.replace('counselorbot-teacher', 'altro.app'))
            with self.assertRaises(ValueError):
                sync_version.sync(root, write=False)

    def test_invalid_version_is_rejected(self):
        with tempfile.TemporaryDirectory() as folder:
            root = self.make_repo(folder, version='v1.0')
            with self.assertRaises(ValueError):
                sync_version.sync(root, write=False)

    def test_repository_is_aligned(self):
        self.assertEqual(sync_version.sync(sync_version.ROOT, write=False)[1], [])


if __name__ == '__main__':
    unittest.main()
